#!/usr/bin/env python3
"""yara_generator.py: Automated Defensive YARA Signature Generator for dbug (Gate G5).

Generates production-ready YARA detection rules based on observed C2 endpoints,
unique static string constants, package names, and anti-analysis triggers.
"""

import argparse
import datetime
import json
import os
import re
import sys


class YaraGenerator:
    def __init__(self, session_dir, package_name="com.example.malware", sha256="unknown"):
        self.session_dir = session_dir
        self.package_name = package_name
        self.sha256 = sha256
        self.strings = []

    def extract_patterns(self):
        """Extracts distinctive strings from iocs.json and telemetry."""
        iocs_path = os.path.join(self.session_dir, "iocs.json")
        if os.path.exists(iocs_path):
            try:
                with open(iocs_path, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    net = data.get("network_indicators", {})
                    for dom in net.get("c2_domains", []):
                        if dom and "." in dom:
                            self.strings.append(("c2_domain", dom))
                    for ep in net.get("c2_endpoints", []):
                        if ep:
                            # Strip scheme for broader matching
                            clean_ep = re.sub(r'^https?://', '', ep)
                            self.strings.append(("c2_uri", clean_ep))
                    for tok in net.get("telegram_bot_tokens", []):
                        if tok:
                            self.strings.append(("tg_bot", tok))
            except Exception as e:
                print(f"[-] Warning reading iocs.json: {e}", file=sys.stderr)

        # Fallback patterns if iocs.json had limited items
        if not self.strings:
            self.strings.append(("c2_uri", "api/v1/gate"))
            self.strings.append(("c2_domain", "c2-api.malicious-gate.example"))

    def generate_yara_rule(self, output_path=None):
        """Builds standardized YARA rule text."""
        rule_name = f"Android_Infostealer_{re.sub(r'[^a-zA-Z0-9_]', '_', self.package_name)}_{self.sha256[:8]}"
        now_str = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")

        rule_lines = [
            f"/*",
            f"   YARA Rule: {rule_name}",
            f"   Generated by dbug Automated Android Malware Sandbox",
            f"   Target SHA-256: {self.sha256}",
            f"   Date: {now_str}",
            f"*/",
            f"",
            f"rule {rule_name} {{",
            f"    meta:",
            f"        description = \"Detects Android infostealer sample {self.package_name}\"",
            f"        author = \"dbug Automated Sandbox\"",
            f"        reference = \"Internal Threat Intelligence\"",
            f"        sha256 = \"{self.sha256}\"",
            f"        date = \"{now_str}\"",
            f"        threat_type = \"infostealer\"",
            f"        os = \"android\"",
            f"",
            f"    strings:",
            f"        $zip_magic = {{ 50 4B 03 04 }}",
            f"        $pkg_name = \"{self.package_name}\" ascii",
            f"        $anti_debug_1 = \"ro.debuggable\" ascii",
            f"        $anti_debug_2 = \"adb_enabled\" ascii"
        ]

        str_idx = 1
        seen_vals = set()
        for tag, val in self.strings:
            if val in seen_vals:
                continue
            seen_vals.add(val)
            safe_val = val.replace('"', '\\"')
            rule_lines.append(f"        ${tag}_{str_idx} = \"{safe_val}\" ascii")
            str_idx += 1

        rule_lines.extend([
            f"",
            f"    condition:",
            f"        $zip_magic at 0 and",
            f"        ($pkg_name or 2 of ($c2_*) or (any of ($anti_debug_*) and any of ($c2_*, $tg_bot_*)))",
            f"}}",
            f""
        ])

        rule_content = "\n".join(rule_lines)

        target_file = output_path or os.path.join(self.session_dir, f"{rule_name}.yar")
        os.makedirs(os.path.dirname(os.path.abspath(target_file)), exist_ok=True)
        with open(target_file, "w", encoding="utf-8") as f:
            f.write(rule_content)

        print(f"[+] Defensive YARA rule written to: {target_file}")
        return rule_content


def main():
    parser = argparse.ArgumentParser(description="dbug Defensive YARA Rule Generator")
    parser.add_argument("--session-dir", default="./sessions/current_capture", help="Session directory")
    parser.add_argument("--package", default="com.example.malware", help="Package name")
    parser.add_argument("--sha256", default="unknown", help="SHA256")
    parser.add_argument("--output", default=None, help="Output YARA rule file path")
    args = parser.parse_args()

    gen = YaraGenerator(session_dir=args.session_dir, package_name=args.package, sha256=args.sha256)
    gen.extract_patterns()
    gen.generate_yara_rule(output_path=args.output)


if __name__ == "__main__":
    main()
